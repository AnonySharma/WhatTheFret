import React, { useState } from 'react';
import { Play, Volume2, ArrowRight, Sparkles, Music } from 'lucide-react';
import { deriveDiatonicHarmony, NoteName, NOTE_NAMES, DiatonicChord } from '../../utils/guitarTheory';
import { guitarAudio } from '../../utils/audioSynth';

export const ModuleDiatonicHarmony: React.FC = () => {
  const [selectedKey, setSelectedKey] = useState<NoteName>('C');
  const [activeDegreeIndex, setActiveDegreeIndex] = useState<number>(0);
  const [isPlayingProgression, setIsPlayingProgression] = useState<boolean>(false);

  const diatonicChords = deriveDiatonicHarmony(selectedKey);
  const activeChord = diatonicChords[activeDegreeIndex];

  const getFreqForNote = (note: NoteName) => {
    const idx = NOTE_NAMES.indexOf(note);
    return 130.81 * Math.pow(2, idx / 12);
  };

  const playDiatonicChord = (chord: DiatonicChord) => {
    const [r, t, f] = chord.notes;
    const freqs = [getFreqForNote(r), getFreqForNote(t), getFreqForNote(f)];
    guitarAudio.strum(freqs, 'down', 32);
  };

  const playProgression = (indices: number[]) => {
    if (isPlayingProgression) return;
    setIsPlayingProgression(true);

    indices.forEach((degIdx, step) => {
      setTimeout(() => {
        setActiveDegreeIndex(degIdx);
        playDiatonicChord(diatonicChords[degIdx]);

        if (step === indices.length - 1) {
          setTimeout(() => setIsPlayingProgression(false), 900);
        }
      }, step * 850);
    });
  };

  const popularKeys: NoteName[] = ['C', 'G', 'D', 'A', 'E', 'F'];

  const progressions = [
    { name: 'Pop Anthem (I - V - vi - IV)', indices: [0, 4, 5, 3] },
    { name: 'Classic Rock / Folk (I - IV - V - I)', indices: [0, 3, 4, 0] },
    { name: 'Jazz Turnaround (ii - V - I)', indices: [1, 4, 0] },
    { name: '50s Ballad (I - vi - ii - V)', indices: [0, 5, 1, 4] },
  ];

  return (
    <div className="space-y-6">
      {/* Title & Core Principle */}
      <div className="bg-stone-900 border border-stone-800 rounded-2xl p-6 shadow-xl space-y-3">
        <div className="flex items-center gap-2">
          <span className="px-2.5 py-1 rounded-lg bg-amber-500/10 text-amber-400 font-mono text-xs font-bold border border-amber-500/20">
            Section 4
          </span>
          <h2 className="text-xl font-bold text-stone-100">Deriving Diatonic Harmony Intuitively</h2>
        </div>
        <p className="text-sm text-stone-300 leading-relaxed">
          You don’t have to guess which chords sound good together in a key; they are mathematically generated by the scale! Sticking to the notes of a major scale and applying <strong className="text-amber-300">"Skip one, take one"</strong> naturally derives:
          <strong className="text-stone-100"> I, IV, V as Major</strong>; <strong className="text-stone-100">ii, iii, vi as Minor</strong>; and <strong className="text-stone-100">vii° as Diminished</strong>.
        </p>
      </div>

      <div className="bg-stone-900 border border-stone-800 rounded-2xl p-6 shadow-xl space-y-6">
        {/* Key Selector */}
        <div className="flex flex-wrap items-center justify-between gap-4">
          <div className="flex items-center gap-2">
            <span className="text-xs font-bold uppercase tracking-wider text-stone-400">Key of:</span>
            <div className="flex items-center gap-1.5">
              {popularKeys.map(key => (
                <button
                  key={key}
                  onClick={() => {
                    setSelectedKey(key);
                    setActiveDegreeIndex(0);
                  }}
                  className={`w-9 h-9 rounded-xl font-extrabold text-sm transition-all border ${
                    selectedKey === key
                      ? 'bg-amber-600 text-white border-amber-500 shadow-md ring-2 ring-amber-500/30'
                      : 'bg-stone-950 text-stone-300 border-stone-800 hover:bg-stone-800'
                  }`}
                >
                  {key}
                </button>
              ))}
            </div>
          </div>

          <span className="text-xs text-stone-400 italic">
            Click any Roman numeral below to inspect its mathematical derivation
          </span>
        </div>

        {/* 7 Diatonic Degree Cards */}
        <div className="grid grid-cols-2 sm:grid-cols-4 lg:grid-cols-7 gap-2.5">
          {diatonicChords.map((chord, idx) => {
            const isSelected = activeDegreeIndex === idx;
            const isMajor = chord.chordType === 'Major';
            const isDim = chord.chordType === 'Diminished';

            return (
              <button
                key={chord.degreeNumeral}
                onClick={() => {
                  setActiveDegreeIndex(idx);
                  playDiatonicChord(chord);
                }}
                className={`p-3 rounded-xl border flex flex-col items-center justify-between transition-all ${
                  isSelected
                    ? 'bg-amber-600/30 border-amber-500 text-amber-200 shadow-lg ring-2 ring-amber-500/40 scale-102'
                    : 'bg-stone-950 border-stone-800 text-stone-300 hover:bg-stone-800/80 hover:border-stone-700'
                }`}
              >
                <div className="flex items-center justify-between w-full">
                  <span className="text-xs font-mono font-bold text-stone-400">{chord.degreeNumeral}</span>
                  <span
                    className={`text-[9px] font-bold px-1.5 py-0.2 rounded ${
                      isMajor
                        ? 'bg-emerald-500/20 text-emerald-400'
                        : isDim
                        ? 'bg-purple-500/20 text-purple-400'
                        : 'bg-blue-500/20 text-blue-400'
                    }`}
                  >
                    {chord.chordType.slice(0, 3)}
                  </span>
                </div>

                <div className="my-2 text-center">
                  <span className="text-xl font-black text-white">{chord.rootNote}</span>
                  <span className="text-xs font-bold text-stone-400 ml-1">
                    {chord.chordType === 'Major' ? '' : chord.chordType === 'Minor' ? 'm' : '°'}
                  </span>
                </div>

                <span className="text-[10px] font-mono text-stone-400">{chord.formula}</span>
              </button>
            );
          })}
        </div>

        {/* Selected Degree "Skip One, Take One" Deep Dive (Recreating PDF Page 4) */}
        {activeChord && (
          <div className="bg-stone-950 border border-stone-800 rounded-xl p-5 space-y-3">
            <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-3">
              <div>
                <div className="flex items-center gap-2">
                  <span className="text-sm font-extrabold text-amber-300">
                    Degree {activeChord.degreeNumeral}: {activeChord.rootNote} {activeChord.chordType}
                  </span>
                  <span className="text-xs px-2 py-0.5 rounded bg-stone-800 text-stone-300 font-mono">
                    [{activeChord.notes.join(' - ')}]
                  </span>
                </div>
                <p className="text-xs text-stone-400 mt-1">{activeChord.function}</p>
              </div>

              <button
                onClick={() => playDiatonicChord(activeChord)}
                className="px-3 py-1.5 rounded-lg bg-amber-600/30 hover:bg-amber-600/50 border border-amber-500/40 text-amber-300 text-xs font-bold flex items-center gap-1.5 shadow-sm active:scale-95 shrink-0"
              >
                <Volume2 className="w-3.5 h-3.5" />
                <span>Hear {activeChord.rootNote}{activeChord.chordType === 'Minor' ? 'm' : ''} Triad</span>
              </button>
            </div>

            {/* Interval Math Breakdown */}
            <div className="bg-stone-900/80 border border-stone-800/80 rounded-lg p-3 text-xs flex flex-wrap items-center gap-3 text-stone-300">
              <span className="font-semibold text-stone-400">Physical Fret Math:</span>
              <span className="px-2 py-0.5 rounded bg-stone-800 text-emerald-400 font-mono font-bold">
                {activeChord.notes[0]} ➔ {activeChord.notes[1]} (+{activeChord.firstJump} frets)
              </span>
              <span>+</span>
              <span className="px-2 py-0.5 rounded bg-stone-800 text-blue-400 font-mono font-bold">
                {activeChord.notes[1]} ➔ {activeChord.notes[2]} (+{activeChord.secondJump} frets)
              </span>
              <span>➔</span>
              <span className="font-bold text-amber-300">
                Formula is +{activeChord.firstJump} then +{activeChord.secondJump} = {activeChord.chordType}!
              </span>
            </div>
          </div>
        )}

        {/* Interactive Diatonic Progression Jukebox */}
        <div className="border-t border-stone-800 pt-5 space-y-3">
          <div className="flex items-center gap-2">
            <Music className="w-4 h-4 text-amber-400" />
            <h4 className="font-bold text-sm text-stone-200">Play Diatonic Chord Progressions</h4>
          </div>
          <p className="text-xs text-stone-400">
            Hear how chords in this key blend together musically. Click any progression to listen:
          </p>

          <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
            {progressions.map((prog, idx) => (
              <button
                key={idx}
                onClick={() => playProgression(prog.indices)}
                disabled={isPlayingProgression}
                className="p-3 rounded-xl bg-stone-950 border border-stone-800 hover:border-amber-500/50 hover:bg-stone-900/60 transition-all text-left flex items-center justify-between group active:scale-98"
              >
                <div>
                  <span className="text-xs font-bold text-stone-200 group-hover:text-amber-300 transition-colors">
                    {prog.name}
                  </span>
                  <div className="flex items-center gap-1.5 mt-1 font-mono text-[11px] text-stone-400">
                    {prog.indices.map((degIdx, i) => {
                      const c = diatonicChords[degIdx];
                      return (
                        <span key={i} className="px-1.5 py-0.2 rounded bg-stone-800 text-stone-300">
                          {c.rootNote}{c.chordType === 'Minor' ? 'm' : ''}
                        </span>
                      );
                    })}
                  </div>
                </div>

                <div className="p-2 rounded-lg bg-stone-800 group-hover:bg-amber-600 group-hover:text-white text-stone-400 transition-colors">
                  <Play className="w-3.5 h-3.5 fill-current" />
                </div>
              </button>
            ))}
          </div>
        </div>
      </div>
    </div>
  );
};
